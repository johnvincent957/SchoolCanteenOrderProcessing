    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
    int selectedRow = jTable1.getSelectedRow();

    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(
            this,
            "Please select an item first!",
            "No Item Selected",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String itemName = jTable1.getValueAt(selectedRow, 1).toString();

    String price = jTable1.getValueAt(selectedRow, 3).toString();

    OrderJFrame order = new OrderJFrame();

    order.setOrderDetails(itemName, price);

    order.setVisible(true);

    this.dispose();
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
    int selectedRow = jTable1.getSelectedRow();

    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(
            this,
            "Please select an item first!",
            "No Item Selected",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String itemName = jTable1.getValueAt(selectedRow, 1).toString();

    double price = Double.parseDouble(
        jTable1.getValueAt(selectedRow, 3).toString()
    );

    int remainingStock = itemStock[selectedRow];

    JOptionPane.showMessageDialog(
        this,
        "ITEM INFORMATION\n\n"
        + "Item Name: " + itemName + "\n"
        + "Price: ₱" + String.format("%.2f", price) + "\n"
        + "Available Items: " + remainingStock + " pieces",
        "Price and Stock View",
        JOptionPane.INFORMATION_MESSAGE
    );
    }//GEN-LAST:event_jButton3ActionPerformed

